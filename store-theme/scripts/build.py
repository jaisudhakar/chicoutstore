#!/usr/bin/env python3
"""Build the store-theme data from the shared catalogue (../scripts/products.csv).

Writes:
  store-theme/html/assets/products.js          products + collections for the HTML pages
  store-theme/html/assets/img/products/*.webp  product photos (copied from html/assets/img/products)
  store-theme/html/assets/img/banner.webp      homepage banner
  store-theme/products-import.csv              Shopify product import (Products → Import)

usage: python3 store-theme/scripts/build.py [--image-base URL]
--image-base is the public folder the import file points Shopify at for photos
(default: this repo's branch on raw.githubusercontent.com).
"""
import argparse
import csv
import json
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = os.path.join(HERE, '..')
REPO = os.path.join(THEME, '..')
SRC_IMG = os.path.join(REPO, 'html', 'assets', 'img')
OUT = os.path.join(THEME, 'html', 'assets')
DEFAULT_IMAGE_BASE = ('https://raw.githubusercontent.com/jaisudhakar/chicoutstore/'
                      'claude/cool-wozniak-ryjlun/store-theme/html/assets/img/products/')

COLLECTIONS = [
    {'id': 'designer', 'label': 'Embroidered & printed', 'type': 'Embroidered & Printed Shirts',
     'blurb': 'Statement shirts with embroidery and bold prints.'},
    {'id': 'solid', 'label': 'Solid shirts', 'type': 'Solid Shirts',
     'blurb': 'Everyday full-sleeve shirts in rich, wearable colours.'},
    {'id': 'checks', 'label': 'Checks & stripes', 'type': 'Checked & Striped Shirts',
     'blurb': 'Tartans, pinstripes and windowpane checks.'},
    {'id': 'tees', 'label': 'Tees & polos', 'type': 'T-Shirts & Polos',
     'blurb': 'Striped long-sleeve tees and zip polos.'},
    {'id': 'denim', 'label': 'Denim & jackets', 'type': 'Denim & Jackets',
     'blurb': 'Washed denim shirts and jackets.'},
    {'id': 'trousers', 'label': 'Trousers', 'type': 'Trousers',
     'blurb': 'Relaxed drawstring trousers and pleated pairs.'},
    {'id': 'jeans', 'label': 'Jeans', 'type': 'Jeans',
     'blurb': 'Straight, wide, baggy and flared fits.'},
]
TOP_SIZES = ['S', 'M', 'L', 'XL', 'XXL']
WAIST_SIZES = ['28', '30', '32', '34', '36']
DESC = {
    'designer': 'A statement shirt with embroidered or printed detail. Wear it tucked into trousers or loose over denim.',
    'solid': 'An everyday full-sleeve shirt in a rich, easy-to-wear colour.',
    'checks': 'A full-sleeve shirt in a classic check or stripe — smart enough for work, easy enough for the weekend.',
    'tees': 'An easy top for off-duty days. Pair it with relaxed trousers or jeans.',
    'denim': 'A washed denim piece with real character.',
    'trousers': 'Comfortable trousers with an easy, relaxed shape.',
    'jeans': 'Everyday jeans in a versatile wash.',
}
DETAILS = {
    'designer': ['Embroidered or printed design', 'Full sleeves with button cuffs', 'Classic collar', 'Gentle wash, iron on reverse'],
    'solid': ['Full sleeves with button cuffs', 'Classic collar', 'Curved hem', 'Machine wash cold, wash dark colours separately'],
    'checks': ['Check or stripe pattern', 'Full sleeves with button cuffs', 'Curved hem', 'Machine wash cold'],
    'tees': ['Easy, relaxed fit', 'Ribbed or tipped trims', 'Machine wash cold'],
    'denim': ['Washed finish', 'Full sleeves', 'Wash inside out, separately'],
    'trousers': ['Relaxed fit', 'Side pockets', 'Machine wash cold'],
    'jeans': ['Five-pocket styling', 'Button and zip fly', 'Wash inside out, separately'],
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--image-base', default=DEFAULT_IMAGE_BASE)
    args = ap.parse_args()
    with open(os.path.join(REPO, 'scripts', 'products.csv'), newline='', encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    col = {c['id']: c for c in COLLECTIONS}

    os.makedirs(os.path.join(OUT, 'img', 'products'), exist_ok=True)
    shutil.copyfile(os.path.join(SRC_IMG, 'banners', 'lookbook.webp'), os.path.join(OUT, 'img', 'banner.webp'))
    products = []
    for r in rows:
        shutil.copyfile(os.path.join(SRC_IMG, 'products', r['id'] + '.webp'), os.path.join(OUT, 'img', 'products', r['id'] + '.webp'))
        bottoms = r['category'] in ('trousers', 'jeans')
        products.append({
            'id': r['id'], 'title': r['name'], 'category': r['category'], 'categoryLabel': col[r['category']]['label'],
            'price': int(r['price']), 'badge': r['badge'], 'image': 'assets/img/products/' + r['id'] + '.webp',
            'optionName': 'Waist' if bottoms else 'Size', 'sizes': WAIST_SIZES if bottoms else TOP_SIZES,
            'description': DESC[r['category']], 'details': DETAILS[r['category']],
        })
    with open(os.path.join(OUT, 'products.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by store-theme/scripts/build.py from scripts/products.csv — edit the CSV and re-run. */\n')
        f.write('window.STORE_COLLECTIONS = ' + json.dumps([{k: c[k] for k in ('id', 'label', 'blurb')} for c in COLLECTIONS], indent=2, ensure_ascii=False) + ';\n')
        f.write('window.STORE_PRODUCTS = ' + json.dumps(products, indent=2, ensure_ascii=False) + ';\n')

    # Shopify product CSV: one row per variant, product fields + image on the first row
    cols = ['Handle', 'Title', 'Body (HTML)', 'Vendor', 'Type', 'Tags', 'Published', 'Option1 Name', 'Option1 Value',
            'Variant SKU', 'Variant Grams', 'Variant Inventory Tracker', 'Variant Inventory Policy', 'Variant Fulfillment Service',
            'Variant Price', 'Variant Requires Shipping', 'Variant Taxable', 'Image Src', 'Image Position', 'Image Alt Text', 'Status']
    with open(os.path.join(THEME, 'products-import.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for p in products:
            body = '<p>' + p['description'] + '</p><ul>' + ''.join('<li>' + d + '</li>' for d in p['details']) + '</ul>'
            tags = [p['category'], p['categoryLabel']] + ([p['badge']] if p['badge'] else [])
            for i, s in enumerate(p['sizes']):
                row = {'Handle': p['id'], 'Option1 Value': s, 'Variant SKU': (p['id'] + '-' + s).upper(), 'Variant Grams': '',
                       'Variant Inventory Policy': 'deny', 'Variant Fulfillment Service': 'manual', 'Variant Price': f"{p['price']:.2f}",
                       'Variant Requires Shipping': 'TRUE', 'Variant Taxable': 'TRUE'}
                if i == 0:
                    row.update({'Title': p['title'], 'Body (HTML)': body, 'Vendor': 'ChicOut', 'Type': col[p['category']]['type'],
                                'Tags': ', '.join(tags), 'Published': 'FALSE', 'Option1 Name': p['optionName'],
                                'Image Src': args.image_base + p['id'] + '.webp', 'Image Position': 1, 'Image Alt Text': p['title'],
                                'Status': 'draft'})
                w.writerow(row)
    print(f'{len(products)} products, {sum(len(p["sizes"]) for p in products)} variants')


if __name__ == '__main__':
    main()
